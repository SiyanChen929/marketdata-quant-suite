def objective_score(
    metrics: dict[str, float],
    max_drawdown_penalty: float = 0.5,
    turnover_penalty: float = 0.25,
    cagr_weight: float = 1.0,
    total_return_weight: float = 0.0,
    trailing_one_year_weight: float = 0.0,
) -> float:
    """Return objective with configurable risk guardrails.

    Defaults reproduce the original risk-adjusted CAGR objective. Return-seeking
    profiles can explicitly add total-return and trailing-return weights while
    keeping drawdown/turnover penalties as guardrails.
    """

    cagr = float(metrics.get("cagr", 0.0))
    total_return = float(metrics.get("total_return", 0.0))
    trailing_one_year_return = float(metrics.get("trailing_one_year_return", 0.0))
    max_drawdown = abs(float(metrics.get("max_drawdown", 0.0)))
    turnover = float(metrics.get("average_turnover", 0.0))
    return (
        float(cagr_weight) * cagr
        + float(total_return_weight) * total_return
        + float(trailing_one_year_weight) * trailing_one_year_return
        - float(max_drawdown_penalty) * max_drawdown
        - float(turnover_penalty) * turnover
    )
