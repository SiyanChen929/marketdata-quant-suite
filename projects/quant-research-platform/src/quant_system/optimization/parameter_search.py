def coarse_grid(grid: dict[str, list[Any]]) -> list[dict[str, Any]]:
    """Return a coarse cartesian grid."""

    keys = list(grid)
    return [dict(zip(keys, values)) for values in product(*(grid[key] for key in keys))]


